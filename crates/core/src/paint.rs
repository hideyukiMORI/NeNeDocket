//! 描画命令の色の意味。

/// 何の色で描くか。実際の色は UI が見え（ダーク・ライト）から決める。閉じた集合（RS-002）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Paint {
    /// 窓の地。
    Background,
    /// 部品の面（入力欄・ボタン・表の行）。
    Surface,
    /// 罫線・区切り線（表の行の間・スクロールバーの線）。部品の境界ではないので淡くてよい。
    Border,
    /// 部品の縁（欄・ボタン・札・チェック・選択箱）。地と面に 3:1 以上（WCAG 1.4.11・ADR 0025）。
    Control,
    /// 文字と印。
    Ink,
    /// 控えめな文字（ヘッダ・ヒント）。
    Muted,
    /// 強調（フォーカスの縁・押している面・チェックの印）。
    Accent,
    /// 強調の上に置く文字。
    OnAccent,
    /// 選択の背景（文字の選択・光らせている候補・選んだ行）。
    Selection,
}
