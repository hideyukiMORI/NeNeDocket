/// 相対輝度 × 10⁷（0〜10⁷）。
#[must_use]
pub fn luminance(rgb: Rgb) -> u64 {
    let linear = |channel: u8| u64::from(LINEAR.get(usize::from(channel)).copied().unwrap_or(0));
    (2_126 * linear(rgb.red()) + 7_152 * linear(rgb.green()) + 722 * linear(rgb.blue())) / 10_000
}

/// 2 色の比が `tenths / 10` 以上か（`(明るい方 + 0.05) / (暗い方 + 0.05)`）。
#[must_use]
pub fn at_least(first: Rgb, second: Rgb, tenths: u64) -> bool {
    let (a, b) = (luminance(first), luminance(second));
    let (lighter, darker) = if a >= b { (a, b) } else { (b, a) };
    (lighter + OFFSET) * 10 >= tenths * (darker + OFFSET)
}

/// 0.05 × 10⁷。
const OFFSET: u64 = 500_000;

/// 部品の境界（1.4.11）。
pub const NON_TEXT: u64 = 30;
/// 文字（1.4.3）。
pub const TEXT: u64 = 45;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn black_and_white_are_twenty_one_to_one_and_grey_sits_between() {
        let (black, white) = (Rgb::new(0, 0, 0), Rgb::new(255, 255, 255));
        assert_eq!(luminance(black), 0);
        assert_eq!(luminance(white), 10_000_000);
        assert!(at_least(black, white, 210));
        assert!(!at_least(black, white, 211));
        // #767676 は白に対して 4.54:1（4.5 を超える最も明るい灰色として知られる）。
        let grey = Rgb::new(0x76, 0x76, 0x76);
        assert!(at_least(grey, white, TEXT));
        assert!(!at_least(Rgb::new(0x77, 0x77, 0x77), white, 46));
        assert!(at_least(white, grey, TEXT));
        assert!(!at_least(grey, grey, NON_TEXT));
    }
}
